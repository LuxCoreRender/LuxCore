"""Build the Blender addon zip: BlendLuxCore HEAD plus the bundled wheels.

usage: addon_zip.py <BlendLuxCore repo> <out zip> <wheel> [<wheel> ...]

The manifest `wheels` entry lists the bundled wheels, so Blender installs
them with the extension. pyluxcore_installation_info.txt holds the hash
luxloader computes for its default PyPI requirement, so luxloader skips the
download and keeps the bundled pyluxcore.
"""
import hashlib, io, pathlib, re, subprocess, sys, tarfile, zipfile

repo, out_zip, *wheels = sys.argv[1:]
wheels = [pathlib.Path(w) for w in wheels]

archive = subprocess.run(["git", "-C", repo, "archive", "--format=tar", "--prefix=blendluxcore/", "HEAD"],
                         check=True, capture_output=True).stdout
loader = subprocess.run(["git", "-C", repo, "show", "HEAD:luxloader/__init__.py"],
                        check=True, capture_output=True, text=True).stdout
version = re.search(r'^PYLUXCORE_VERSION = "([^"]+)"', loader, re.M).group(1)
info = ("# This file is intended to store information about pyluxcore installation.\n"
        "# It is used to determine whether a new installation is necessary at each\n"
        "# startup.\n"
        "# Only one entry should be different from 'None', it indicates from which\n"
        "# source the installation was taken.\n"
        "#\n"
        "# This file is automatically generated and should not be edited manually.\n\n"
        "[WHEELS]\n"
        f"hash = {hashlib.sha256(f'pyluxcore=={version}'.encode()).hexdigest()}\n\n")
wheel_list = ", ".join(f'"wheels/{w.name}"' for w in wheels)

with tarfile.open(fileobj=io.BytesIO(archive)) as tar, zipfile.ZipFile(out_zip, "w", zipfile.ZIP_DEFLATED) as zout:
    for member in tar.getmembers():
        if not member.isfile():
            continue
        data = tar.extractfile(member).read()
        if member.name == "blendluxcore/blender_manifest.toml":
            text, count = re.subn(r"^wheels = \[.*\](?=\r?$)", f"wheels = [{wheel_list}]", data.decode(), flags=re.M)
            assert count == 1, "manifest wheels entry not found"
            data = text.encode()
        zout.writestr(member.name, data)
    zout.writestr("blendluxcore/pyluxcore_installation_info.txt", info)
    for w in wheels:
        zout.write(w, f"blendluxcore/wheels/{w.name}", compress_type=zipfile.ZIP_STORED)
print("wrote", out_zip)
